def render():
    src = open(SRC, encoding="utf-8").read()
    md = markdown.Markdown(extensions=["tables", "fenced_code", "sane_lists", "toc"],
                           extension_configs={"toc": {"slugify": slug}})
    body = md.convert(src)
    # the first heading becomes the cover line with the logo
    title = re.search(r"<h1[^>]*>(.*?)</h1>", body, re.S).group(1)
    logo = base64.b64encode(open(LOGO, "rb").read()).decode()
    cover = ('<div class="cover"><img src="data:image/png;base64,%s" alt=""><div><h1>%s</h1>'
             '<div class="sub">Installation and operation of UntrashOS on the Zyxel NAS542</div></div></div>' % (logo, title))
    body = re.sub(r"<h1[^>]*>.*?</h1>", lambda m: cover, body, count=1, flags=re.S)
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\n"
            "<title>%s</title>\n<!-- generated by tools/manual/build.py from README.md; do not edit -->\n"
            "<style>%s</style></head>\n<body><main>\n%s\n</main></body></html>\n" % (
                html.escape(re.sub(r"<[^>]+>", "", title)), CSS, body))


def pdf(page):
    """Chromium stores WebP images in a PDF as raw (Flate) bitmaps; JPEG ones
    go in as they are.  So the print copy of the page uses JPEG screenshots."""
    from PIL import Image
    with tempfile.TemporaryDirectory(prefix="manual-") as tmp:
        os.makedirs(os.path.join(tmp, "img"))
        for n in set(re.findall(r'src="img/([^"]+)\.webp"', page)):
            Image.open(os.path.join(UG, "img", n + ".webp")).convert("RGB").save(
                os.path.join(tmp, "img", n + ".jpg"), quality=82, optimize=True, progressive=True)
        printed = os.path.join(tmp, "print.html")
        open(printed, "w", encoding="utf-8").write(re.sub(r'src="img/([^"]+)\.webp"', r'src="img/\1.jpg"', page))
        subprocess.run(["chromium", "--headless=new", "--no-sandbox", "--disable-gpu", "--user-data-dir=" + os.path.join(tmp, "profile"),
                        "--no-pdf-header-footer", "--run-all-compositor-stages-before-draw",
                        "--virtual-time-budget=10000", "--print-to-pdf=" + OUT_PDF, "file://" + printed],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=180)


def main():
    page = render()
    missing = [i for i in re.findall(r'<img[^>]+src="(img/[^"]+)"', page) if not os.path.isfile(os.path.join(UG, i))]
    unused = sorted(set(os.listdir(os.path.join(UG, "img"))) - {os.path.basename(i) for i in re.findall(r'src="img/([^"]+)"', page)})
    if missing:
        sys.exit("manual: missing images: %s" % ", ".join(missing))
    if unused:
        print("manual: images not used by README.md: %s" % ", ".join(unused))
    if "--check" in sys.argv:
        cur = open(OUT_HTML, encoding="utf-8").read() if os.path.isfile(OUT_HTML) else ""
        if cur != page:
            sys.exit("manual: docs/user-guide/manual.html is out of date: run make manual")
        if not os.path.isfile(OUT_PDF):
            sys.exit("manual: UntrashOS-User-Guide.pdf is missing: run make manual")
        print("manual: up to date")
        return
    open(OUT_HTML, "w", encoding="utf-8").write(page)
    pdf(page)
    print("manual: %s, %s (%d KB)" % (os.path.relpath(OUT_HTML, ROOT), os.path.relpath(OUT_PDF, ROOT),
                                     os.path.getsize(OUT_PDF) // 1024))


if __name__ == "__main__":
    main()
